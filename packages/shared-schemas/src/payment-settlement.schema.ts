/** One bill on the consolidated receipt. */
export interface SettlementReceiptItem {
  paymentId: string;
  transactionId: string;
  /** The bill's own receipt, «RCP-…». */
  receiptNumber: string;
  /** «INV-…», or null for a bill raised before migration 0079. */
  invoiceNumber: string | null;
  title: string;
  /** The billing period the bill is for, as stored (`ONCE`, `2026`, `2026-Q3`, …). */
  periodKey: string;
  dueDate: string;
  /**
   * The cadastre parcels and units the bill was assessed on, from its
   * assessment's lines, de-duplicated. Empty for a flat or one-off charge. The
   * screen words them («عقار 123 — شقة»), so the wire stays language-neutral.
   */
  properties: Array<{ propertyNumber: string | null; unitType: string | null; unitCode: string | null }>;
  /** The credit applied to the bill, in its currency. */
  amount: number;
  currency: string;
  /** True once this bill's row has been reversed. */
  reversed: boolean;
}

/** The consolidated receipt, as printed and reprinted. */
export interface SettlementReceipt {
  id: string;
  /** «BRC-2610-0001». */
  number: string;
  occurredAt: string;
  method: PaymentMethod;
  citizen: {
    id: string;
    fullName: string;
    fatherName: string | null;
    phone: string | null;
    whatsapp: string | null;
  };
  collectorName: string | null;
  externalRef: string | null;
  recordedByName: string | null;
  items: SettlementReceiptItem[];
  /** Per currency, what the bills were credited with. */
  totals: Record<string, number>;
  /** CASH only; null otherwise. */
  tender: {
    local: number;
    localCurrency: string;
    foreign: number;
    foreignCurrency: string | null;
    exchangeRate: number | null;
    changeGiven: number;
  } | null;
  /** True when this answers a retry with the settlement already recorded. */
  replayed?: boolean;
}
