import { z } from 'zod';
import { uuid } from './primitives';
import { paymentMethodSchema, type PaymentMethod } from './fee.schema';
import { hasAtMostTwoDecimals } from './money-amount';
import { roundRate } from './cash-policy';

/**
 * «تسديد الفواتير المحددة» — one citizen settling several bills in one act.
 * Design: docs/finance.md §3.7.
 *
 * Each bill still gets its own ledger row and its own «RCP-» receipt number, so
 * a reprint, a reversal and the treasury's entries keep working bill by bill.
 * The settlement (`payment_settlements`, 0085) holds what belongs to the whole
 * set: the «BRC-» master number, the notes handed over, the change handed back,
 * and the press's retry key.
 *
 * All or nothing: every bill selected ends PAID, or nothing is written. Notes
 * that do not cover the whole set are refused (`BULK_SETTLE_TENDER_SHORT`); the
 * clerk unticks a bill to pay less.
 */

/** The most bills one press settles. */
export const BULK_SETTLE_MAX_BILLS = 50;

const money = (max: number) =>
  z.coerce
    .number({ invalid_type_error: 'المبلغ يجب أن يكون رقماً' })
    .min(0, 'المبلغ لا يمكن أن يكون سالباً')
    .max(max)
    .refine(hasAtMostTwoDecimals, 'منزلتان عشريتان على الأكثر');

/**
 * The notes handed over, on a cash settlement.
 *
 * `local` is in the municipality's own currency (الإعدادات → العملة الأساسية);
 * `foreign` is in `foreignCurrency`, taken at the municipality's official rate.
 * There is no rate in the request: a settlement of several bills uses the
 * official one, and a different rate for one payment stays a single-bill act
 * (`settlePaymentSchema`), where it is asked for with a reason.
 */
export const bulkTenderSchema = z
  .object({
    // Bounded by the column (DECIMAL(14,2)), so an absurd figure is a 422, not a 500.
    local: money(999_999_999_999).default(0),
    foreign: money(1_000_000_000).default(0),
    foreignCurrency: z.enum(['USD', 'EUR']).default('USD'),
  })
  .superRefine((tender, ctx) => {
    if (tender.local <= 0 && tender.foreign <= 0) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['local'], message: 'أدخل المبلغ المستلم' });
    }
  });

export type BulkTender = z.infer<typeof bulkTenderSchema>;

export const bulkSettlePaymentsSchema = z
  .object({
    /** Whose bills. Every bill must be theirs (`BULK_SETTLE_CITIZEN_MISMATCH`). */
    citizenId: uuid,
    paymentIds: z
      .array(uuid)
      .min(1, 'اختر فاتورة واحدة على الأقل')
      .max(BULK_SETTLE_MAX_BILLS, `لا يمكن تسديد أكثر من ${BULK_SETTLE_MAX_BILLS} فاتورة دفعة واحدة`)
      .refine((ids) => new Set(ids).size === ids.length, 'فاتورة مكرّرة في القائمة'),
    method: paymentMethodSchema,
    /** The محصّل who took the money. Required for COLLECTOR, refused otherwise. */
    collectedById: uuid.optional(),
    /** The Whish transfer's own number. Required for WHISH_MONEY, refused otherwise. */
    whishTransactionRef: z.string().trim().min(4, 'رقم العملية قصير جداً').max(80).optional(),
    /** The notes handed over. Required for CASH, refused otherwise. */
    tendered: bulkTenderSchema.optional(),
    note: z.string().trim().max(500).optional(),
    /**
     * One id per press of «تسديد», generated by the dialog. A retry after a lost
     * response sends the same id and gets the first settlement back.
     */
    clientRequestId: uuid,
  })
  .superRefine((data, ctx) => {
    if (data.method === 'CASH' && !data.tendered) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['tendered'], message: 'أدخل المبلغ المستلم' });
    }
    if (data.method !== 'CASH' && data.tendered) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ['tendered'],
        message: 'الدفع بعملتين متاح للدفع النقدي فقط',
      });
    }
    if (data.method === 'COLLECTOR' && !data.collectedById) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ['collectedById'],
        message: 'اختر المحصّل الذي استلم المبلغ',
      });
    }
    if (data.method !== 'COLLECTOR' && data.collectedById) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['collectedById'], message: 'المحصّل للتحصيل الميداني فقط' });
    }
    if (data.method === 'WHISH_MONEY' && !data.whishTransactionRef) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ['whishTransactionRef'],
        message: 'أدخل رقم عملية التحويل',
      });
    }
    if (data.method !== 'WHISH_MONEY' && data.whishTransactionRef) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ['whishTransactionRef'],
        message: 'رقم العملية لتحويل Whish فقط',
      });
    }
  });

export type BulkSettlePayments = z.infer<typeof bulkSettlePaymentsSchema>;

